def collect_patch_anchor(paths: list[str]) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for value in paths:
        path = Path(value)
        payload = load_json(path)
        if not isinstance(payload, list):
            raise ValueError(f"patch anchor summary must be a list: {path}")
        for item in payload:
            if not isinstance(item, dict):
                continue
            rows.append(
                {
                    "source": str(path),
                    "dataset": item.get("dataset", ""),
                    "method": item.get("method", ""),
                    "f1": fmt(item.get("f1")),
                    "em": fmt(item.get("em")),
                    "avg_nll": fmt(item.get("avg_nll")),
                    "ppl": fmt(item.get("ppl", item.get("avg_ppl"))),
                    "ttft_ms": fmt(item.get("ttft_ms"), 3),
                    "payload_mb": fmt(item.get("payload_mb"), 3),
                }
            )
    rows.sort(key=lambda row: (str(row["dataset"]), str(row["method"]), str(row["source"])))
    return rows


def route_counts(row: dict[str, Any]) -> tuple[int | None, int | None]:
    patch_layers = row.get("patch_layers")
    reuse_layers = row.get("reuse_layers")
    patch_n = len(patch_layers) if isinstance(patch_layers, list) else None
    reuse_n = len(reuse_layers) if isinstance(reuse_layers, list) else None
    return patch_n, reuse_n


def infer_full_ppl(row: dict[str, Any]) -> float | None:
    ppl = maybe_float(row.get("ppl"))
    delta = maybe_float(row.get("ppl_delta"))
    if ppl is None or delta is None:
        return None
    return ppl - delta


def collect_route_metrics(paths: list[str]) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for value in paths:
        path = Path(value)
        payload = load_json(path)
        metric_rows = payload.get("rows") if isinstance(payload, dict) else payload
        if not isinstance(metric_rows, list):
            raise ValueError(f"route metrics must contain a rows list: {path}")
        for item in metric_rows:
            if not isinstance(item, dict):
                continue
            dataset = infer_dataset(item, path)
            patch_n, reuse_n = route_counts(item)
            full_ppl = infer_full_ppl(item)
            ppl_rel = safe_ratio(item.get("ppl"), full_ppl)
            rows.append(
                {
                    "source": str(path),
                    "dataset": dataset,
                    "route_name": item.get("route_name", ""),
                    "status": item.get("status", ""),
                    "patch_n": "" if patch_n is None else patch_n,
                    "reuse_n": "" if reuse_n is None else reuse_n,
                    "full_f1": fmt(item.get("full_f1")),
                    "scd_f1": fmt(item.get("f1")),
                    "f1_retention": fmt(item.get("f1_retention")),
                    "full_em": fmt(item.get("full_em")),
                    "scd_em": fmt(item.get("em")),
                    "em_delta": fmt(item.get("em_delta")),
                    "full_ppl": fmt(full_ppl),
                    "scd_ppl": fmt(item.get("ppl")),
                    "ppl_rel_increase_pct": "" if ppl_rel is None else f"{(ppl_rel - 1.0) * 100.0:.3f}",
                    "full_avg_nll": fmt(item.get("full_avg_nll")),
                    "scd_avg_nll": fmt(item.get("avg_nll")),
                    "avg_nll_delta": fmt(item.get("avg_nll_delta")),
                    "full_ttft_ms": fmt(item.get("full_ttft_ms"), 3),
                    "scd_ttft_ms": fmt(item.get("ttft_ms", item.get("estimated_ttft_ms")), 3),
                }
            )
    rows.sort(
        key=lambda row: (
            str(row["source"]),
            int(row["reuse_n"]) if row["reuse_n"] != "" else -1,
            str(row["route_name"]),
        )
    )
    return rows


def write_route_curves(out_dir: Path, route_rows: list[dict[str, Any]]) -> list[str]:
    outputs: list[str] = []
    by_dataset: dict[str, list[dict[str, Any]]] = {}
    for row in route_rows:
        dataset = str(row.get("dataset") or "unknown")
        if row.get("status") != "ok" or row.get("reuse_n") == "":
            continue
        by_dataset.setdefault(dataset, []).append(row)
    curve_fields = [
        "dataset",
        "route_name",
        "patch_n",
        "reuse_n",
        "full_f1",
        "scd_f1",
        "f1_retention",
        "full_em",
        "scd_em",
        "full_ppl",
        "scd_ppl",
        "ppl_rel_increase_pct",
        "scd_ttft_ms",
        "source",
    ]
    for dataset, rows in sorted(by_dataset.items()):
        safe = "".join(ch if ch.isalnum() or ch in {"-", "_"} else "_" for ch in dataset.lower())
        csv_name = f"route_curve_{safe}.csv"
        md_name = f"route_curve_{safe}.md"
        svg_name = f"route_curve_{safe}.svg"
        write_csv(out_dir / csv_name, rows, curve_fields)
        write_md(out_dir / md_name, f"{dataset} Route Curve", rows, curve_fields)
        svg = build_svg_curve(dataset, rows)
        if svg:
            (out_dir / svg_name).write_text(svg, encoding="utf-8")
            outputs.append(svg_name)
        outputs.extend([csv_name, md_name])
    return outputs


